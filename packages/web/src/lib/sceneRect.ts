/** สัดส่วนภาพฉาก 1760 × 1097 — ห้ามเปลี่ยน (สเปกข้อ 7.2) */
export const SCENE_AR = 1760 / 1097;

/**
 * เพดานการ crop: กว้างได้ไม่เกิน 145% ของขนาดแบบ contain
 * = ยอมให้ภาพล้นออกนอกจอได้ราว 45% ต่อแกน ส่วนที่เหลือโชว์ภาพเบลอด้านหลัง
 *
 * **ต้นแบบใช้ 1.24 — ขยายเป็น 1.45 ตามที่เจ้าของงานสั่ง** (ดู docs/DESIGN_SOURCE.md ข้อ 19)
 * ที่ 1.24 แถบเบลอจะโผล่ทันทีที่หน้าต่างสัดส่วนเกิน 1.99:1 ซึ่งรวมถึง
 * เบราว์เซอร์ขยายเต็มจอบนจอ 1080p (viewport จริงราว 1920×955 = 2.01:1)
 * — ไม่ใช่เคสหายาก แต่เป็นค่ามาตรฐานของคนส่วนใหญ่
 *
 * ที่ 1.45 หน้าต่าง 16:9 ทุกแบบเต็มจอ และยังเห็นครบทั้งหลอดไฟบนสุด (y 14.5%)
 * กับหมุดโซนล่างสุด (y 77%) — เสียแค่ขอบล่างสุดของภาพแปลง
 * จอ 21:9 ยังมีแถบอยู่ เพราะต้องเห็นแนวตั้ง 75.5% แต่สัดส่วนนั้นให้ได้แค่ 62%
 * จะเต็มจอก็ต่อเมื่อยอมให้หลอดไฟหรือแปลงล่างหายไป ซึ่งไม่คุ้ม
 */
export const MAX_CROP = 1.45;

/** จุดยึดแนวตั้งเวลาภาพสูงกว่าจอ — เอียงขึ้น 42% เพื่อให้แปลงล่างไม่โดนตัด */
export const CROP_ANCHOR_Y = 0.42;

export interface SceneRect {
  readonly l: number;
  readonly t: number;
  readonly w: number;
  readonly h: number;
}

/**
 * พอร์ตตรงจาก `sceneRect()` ในต้นแบบ
 *
 * เต็มจอจริง: cover viewport แต่จำกัด crop ไว้ ~24% ต่อแกน
 * ส่วนของ viewport ที่เหลือจะเห็นภาพเดียวกันแบบเบลออยู่ข้างหลัง
 * จอแคบ (สูงกว่ากว้าง) จะได้ผลลัพธ์แบบ contain — ไม่มีการยืดภาพในทุกกรณี
 * เพราะความสูงคำนวณจากความกว้างหารด้วย AR เสมอ
 */
export function sceneRect(vw: number, vh: number): SceneRect {
  const containW = Math.min(vw, vh * SCENE_AR);
  const coverW = Math.max(vw, vh * SCENE_AR);
  const w = Math.min(coverW, containW * MAX_CROP);
  const h = w / SCENE_AR;
  const t = h >= vh ? -(h - vh) * CROP_ANCHOR_Y : (vh - h) * 0.5;
  return { l: (vw - w) / 2, t, w, h };
}
